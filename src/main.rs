// принимает путь к файлу (строку) и вставляет содержимое этого файла 
// прямо в код так
include!(
    concat!(    // Сцепляет литералы в статический строковый срез.
        env!("OUT_DIR"),    // подставляет значение переменной окружения OUT_DIR в виде строкового литерала.
        "/bindings.rs"
    )
) ;

fn main() {
    let x = 10 ;
    let y = 20 ;
    unsafe {
        println!("{x} + {y} = {}", add(x, y)) ;
    }   // Out: 10 + 20 = 30
}
